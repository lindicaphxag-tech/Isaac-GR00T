"""Generate a minimal upstream-native SemRepair adoption skeleton.

The command does not claim adoption.  It creates small, auditable files that a
robotics repository can review and maintain in its own tree.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


SUPPORTED_INTEGRATIONS = {
    "native-regression",
    "source-boundary-ci",
    "runtime-refinement",
}


def build_adoption_manifest(
    *,
    repository: str,
    contract_id: str,
    integration_type: str,
    maintained_path: str,
    semantic_layer: str,
) -> dict[str, object]:
    if "/" not in repository:
        raise ValueError("repository must be owner/name")
    if not contract_id:
        raise ValueError("contract_id must be non-empty")
    if integration_type not in SUPPORTED_INTEGRATIONS:
        raise ValueError(
            f"integration_type must be one of {sorted(SUPPORTED_INTEGRATIONS)}"
        )
    if not maintained_path:
        raise ValueError("maintained_path must be non-empty")
    if not semantic_layer:
        raise ValueError("semantic_layer must be non-empty")

    return {
        "schema_version": 1,
        "repository": repository,
        "integration_type": integration_type,
        "semantic_layer": semantic_layer,
        "contract_ids": [contract_id],
        "maintained_path": maintained_path,
        "status": "candidate",
        "claim_boundary": (
            "This manifest records an integration candidate. It becomes external "
            "adoption evidence only when maintained in the named external repository."
        ),
    }


