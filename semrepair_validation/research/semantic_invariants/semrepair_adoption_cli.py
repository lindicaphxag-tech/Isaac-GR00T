def render_source_ci() -> str:
    return """name: SemRepair semantic boundary

on:
  pull_request:
  push:

jobs:
  semantic-boundary:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - name: Install SemRepair release candidate
        run: |
          python -m pip install \
            "git+https://github.com/lindicaphxag-tech/Isaac-GR00T.git@semrepair-v0.3-rc1#subdirectory=semrepair_validation"
      - name: Check semantic boundary
        run: semrepair-source --manifest semrepair.json --json
"""


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate a minimal SemRepair upstream-adoption skeleton"
    )
    parser.add_argument("--repository", required=True)
    parser.add_argument("--contract-id", required=True)
    parser.add_argument(
        "--integration-type",
        choices=sorted(SUPPORTED_INTEGRATIONS),
        default="native-regression",
    )
    parser.add_argument("--semantic-layer", required=True)
    parser.add_argument("--maintained-path", default="tests/test_semantic_contract.py")
    parser.add_argument("--output-dir", type=Path, default=Path(".semrepair-adoption"))
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    out = args.output_dir
    if out.exists() and any(out.iterdir()) and not args.force:
        raise SystemExit(
            f"{out} is not empty; use --force or choose another output directory"
        )
    out.mkdir(parents=True, exist_ok=True)

    manifest = build_adoption_manifest(
        repository=args.repository,
        contract_id=args.contract_id,
        integration_type=args.integration_type,
        maintained_path=args.maintained_path,
        semantic_layer=args.semantic_layer,
    )
    (out / "semrepair-adoption.json").write_text(
        json.dumps(manifest, indent=2) + "\n",
        encoding="utf-8",
    )

    if args.integration_type == "native-regression":
        (out / "test_semantic_contract.py").write_text(
            render_native_regression(args.contract_id),
            encoding="utf-8",
        )
    elif args.integration_type == "source-boundary-ci":
        (out / "semrepair-source-check.yml").write_text(
            render_source_ci(),
            encoding="utf-8",
        )
        (out / "semrepair.json").write_text(
            json.dumps(
                {
                    "schema_version": 1,
                    "producer": {
                        "path": "path/to/producer.py",
                        "base_type": {"role": "action", "entity": "replace-me"},
                    },
                    "consumer": {
                        "path": "path/to/consumer.py",
                        "base_type": {"role": "action", "entity": "replace-me"},
                    },
                    "rules": [],
                    "adapters": [],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
    else:
        (out / "RUNTIME_REFINEMENT.md").write_text(
            "# Runtime refinement integration\n\n"
            "Wire the owner-boundary execution/sensor receipt into the semantic "
            "refinement path. Do not relabel requested->executed or stale->fresh "
            "with a pure adapter.\n",
            encoding="utf-8",
        )

    print(out)


if __name__ == "__main__":
    main()
